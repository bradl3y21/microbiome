"""Render ``docs/CALIBRATION.md`` from the targets file and the committed fit, so the document cannot drift from the data."""

from __future__ import annotations

import json
from pathlib import Path

from ..genome.calibration import CALIBRATION_FILE
from ..genome.parser import _PROJECT_ROOT
from .targets import load_targets

DOC_FILE = Path("docs") / "CALIBRATION.md"
ORGANISM_NAME = {"GCF_000005845.2": "E. coli K-12 MG1655", "GCF_000009045.1": "B. subtilis 168", "GCF_000006765.1": "P. aeruginosa PAO1",
                 "GCF_000010465.1": "S. aureus Newman", "GCF_000012685.1": "M. xanthus DK 1622", None: "(all / water)"}
ROLE_ORDER = ("fit", "held_out", "range", "assumed", "reference")
ROLE_TITLE = {
    "fit": "Matched by construction (fit targets)",
    "held_out": "Held out: measured in the simulation after the fit",
    "range": "Must lie inside a published range",
    "assumed": "Assumed (no direct measurement)",
    "reference": "Recorded but deliberately not reproduced",
}


def _fmt(value, digits=4) -> str:
    if value is None:
        return "-"
    if isinstance(value, float) and (abs(value) >= 1e5 or (0 < abs(value) < 1e-3)):
        return f"{value:.3g}"
    return f"{value:.{digits}g}"


def _target_text(row) -> str:
    if row["sd"] is not None and row["target"] is not None:
        return f"{_fmt(row['target'])} +/- {_fmt(row['sd'])}"
    if row["range"] is not None:
        return f"{_fmt(row['range'][0])} to {_fmt(row['range'][1])}"
    return _fmt(row["target"])


def render(project_root=None) -> str:
    root = Path(project_root).resolve() if project_root is not None else _PROJECT_ROOT
    ts = load_targets(root)
    fit = json.loads((root / CALIBRATION_FILE).read_text(encoding="utf-8"))
    rows = {r["id"]: r for r in fit["report"]}
    out: list[str] = []
    w = out.append
    w("# Calibration of the realism layer against published data\n")
    w("This file is generated by `python -m microbiome.calibration report` from `data/calibration_targets.json` and "
      "`data/calibration_fit.json`; `tests/test_calibration.py` fails if it is out of date.\n")
    w("## What this does and does not show\n")
    w("Every number the simulation produces for growth, uptake, swimming and chemotaxis was first a guess. Here each is set "
      "against a measurement from the literature, read from the cited text (the targets file keeps the evidence and the "
      "source of each). Two kinds of result must not be confused:\n")
    w("* **Matched by construction.** A free parameter was solved so the simulation reproduces the number. Agreement is "
      "guaranteed and says nothing about whether the model is right.")
    w("* **Held out.** The number was not used in any fit. Agreement here is the only evidence the model's structure, rather "
      "than its tuning, is sound, and it is weak: there are few such checks and they are consistency checks, not "
      "independent experiments.\n")
    w("Nothing was compared with data for a *population* (a growth curve, a colony, a competition) and nothing here "
      "validates the ecology. Four organisms are fitted to batch growth on glucose with air (M. xanthus, which does not use "
      "sugar, only to its gliding speed, reversals and cell length).\n")

    w("## Fitted parameters\n")
    w("| Organism | Parameter | Value | Fitted to |\n| --- | --- | --- | --- |")
    fitted_to = {
        "uptake_scale": "specific glucose uptake rate (not M. xanthus: it does not grow on sugar)", "biomass_scale": "growth rate (the same)",
        "overflow_scale": "oxygen uptake (E. coli) or acetate production (B. subtilis); not fitted for the others",
        "division_mass_scale": "dry mass per cell (E. coli), cell volume (S. aureus), cell length (M. xanthus); unchanged for B. subtilis and P. aeruginosa (no data)",
        "motility_scale": "swimming speed (B. subtilis, P. aeruginosa) or gliding speed (M. xanthus)",
        "run_time_s": "mean run before a reversal (P. aeruginosa; 0 = the shared E. coli tumble rate)",
        "turn_mean_deg": "mean reorientation at a reversal (P. aeruginosa)", "turn_sd_deg": "its spread",
        "maintenance_mmol_glc_gdw_h": "maintenance coefficient (measured for B. subtilis; E. coli's assumed value is a placeholder for the others)",
        "storage_scale": "assumed: no data",
    }
    for accession, values in fit["organisms"].items():
        for key, value in values.items():
            w(f"| {ORGANISM_NAME[accession]} | `{key}` | {_fmt(value, 5)} | {fitted_to.get(key, '')} |")
    shared_note = {
        "swim_speed_scale": "E. coli swimming speed (the B. subtilis factor above scales it to 18.6 um/s)", "tumble_rate_per_s": "1 / mean run time",
        "tumble_angle_mean_deg": "mean reorientation (this is the underlying normal; the clipped angle has mean 62.5 degrees)",
        "tumble_angle_sd_deg": "spread of reorientation (underlying normal; the clipped angle has sd 36 degrees)",
        "chemotaxis_gain": "peak chemotactic drift = 30 % of swimming speed",
        "reversal_rate_per_s": "1 / mean time between reversals of a gliding M. xanthus cell (7.5 min)",
    }
    for key, value in fit["shared"].items():
        w(f"| both | `RealismConfig.{key}` | {_fmt(value, 6)} | {shared_note.get(key, '')} |")
    w("")
    w("The factors multiply the D2 gene-derived values only in the realism layer; the plain D1 world keeps the D2 numbers. "
      "Assumptions that were not measured: " + "; ".join(f"**{k}**: {v}" for k, v in fit["assumptions"].items()) + ".\n")

    w("## Results\n")
    for role in ROLE_ORDER:
        subset = [t for t in ts.targets if t.role == role]
        if not subset:
            continue
        w(f"### {ROLE_TITLE[role]}\n")
        w(f"_{ts_roles(root)[role]}_\n")
        w("| Quantity | Organism | Published | Simulated | Unit | Result | Source |\n| --- | --- | --- | --- | --- | --- | --- |")
        for t in subset:
            row = rows.get(t.id)
            measured = "-" if row is None or row["measured"] is None else _fmt(row["measured"])
            mark = "-" if row is None or row["ok"] is None else ("ok" if row["ok"] else "**FAILS**")
            note = "" if row is None or not row["note"] else f" ({row['note']})"
            source = ts.sources.get(t.raw.get("source"), {}).get("citation", "none")
            doi = ts.sources.get(t.raw.get("source"), {}).get("doi")
            link = f"[{t.raw.get('source')}](https://doi.org/{doi})" if doi else str(t.raw.get("source") or "-")
            w(f"| {t.quantity} (`{t.id}`){note} | {ORGANISM_NAME.get(t.organism, t.organism)} | {_target_text(row) if row else _fmt(t.value)} | "
              f"{measured} | {t.unit} | {mark} | {link} |")
        w("")

    cycle = fit.get("validation_cycle")
    if cycle:
        w("## Whole-cell-cycle check\n")
        w("A cell born at half the division mass, in growth medium, simulated until it divides (not just an instantaneous rate):\n")
        w("| Organism | Simulated time to divide | Expected from the growth rate plus commitment | Doubling time implied by the growth rate |\n| --- | --- | --- | --- |")
        for accession, result in cycle.items():
            w(f"| {ORGANISM_NAME[accession]} | {result['mean_division_time_s'] / 60:.1f} min | {result['expected_s'] / 60:.1f} min | {result['doubling_time_min_equivalent']:.1f} min |")
        w("")

    w("## Not calibrated at all\n")
    w("These are still the original, unmeasured guesses (each is a named parameter in `docs/REALISM.md`): the lag-phase time "
      "constants; starvation death rate and time constant; sporulation commitment thresholds (only the 8 h duration is "
      "checked); germination rate; quorum-signal production and threshold; biofilm matrix time constants and its protection "
      "factors; toxin production and potency; acid damage; pH buffering; the receptor adaptation time (2 s) and sensing "
      "constant; collision stiffness and cohesion; transformation rates; the Michaelis constants of oxygen and acetate "
      "and every constant for lactose; the B. subtilis glucose Ks; B. subtilis cell mass. Rod width and wet volume per "
      "gram of dry mass (3.3 um^3/pg, against 3.1 derived from Neidhardt 1996 with an assumed density) are plausible, "
      "not fitted.\n")
    w("## Known mismatches\n")
    w("* **Acetate overflow depends on sugar level, not growth rate.** Basan et al. 2015 find none below 0.76/h in batch "
      "culture (K-12 NCM3722 in MOPS medium); the oxygen uptake used for the E. coli fit (strain C-3000, M9) implies about "
      "21 % of glucose carbon leaves as acetate at 0.65/h. The two data sets disagree by strain and medium, and the model "
      "follows the one it was fitted to. It does reproduce Kayser et al.'s observation that glucose-limited chemostat "
      "growth below D = 0.3/h makes no acetate.")
    w("* **Tumbles take no time.** Cells are about 30 % faster on average than the same cells would look in tracking "
      "(0.19 s of every 0.83 s is a tumble).")
    w("* **Oxygen diffuses 30 % too slowly** (1400 against 2000 um^2/s) because the explicit scheme is unstable above about "
      "1500 at this step; acetate is capped likewise.")
    w("* **All swimmers share every sugar Ks and the chemotactic gain**; each has its own swimming speed, and P. aeruginosa its own "
      "run time and reversal angle. Chemotaxis was calibrated on E. coli alone.")
    w("* **Maintenance of P. aeruginosa, S. aureus and M. xanthus is E. coli's assumed value**, a placeholder (no coefficient was found).")
    w("* **Biomass is glucose-equivalent in the model** (40 % carbon by mass, against about 48 % for real dry matter), so carbon fractions derived from the model, such as the 21 % of glucose carbon that the E. coli fit sends to acetate, are internally consistent but only approximate; growth, uptake and dry mass are matched in their own units.")
    w("* **Cell size does not vary with growth rate** (the Schaechter growth law is not modelled): the division mass is "
      "fixed at the value for 0.65/h.\n")

    w("## Sources\n")
    for key, source in ts.sources.items():
        doi = f"https://doi.org/{source['doi']}" if source.get("doi") else "no DOI recorded"
        w(f"* **{key}**: {source['citation']} ({doi}). Read via {source['read_via']}.")
    w("\n## Reproducing\n")
    w("```\npython -m microbiome.calibration fit      # solves the parameters and rewrites data/calibration_fit.json\n"
      "python -m microbiome.calibration check    # measures every target against the committed fit (exit 1 on a failure)\n"
      "python -m microbiome.calibration cycle    # the whole-cell-cycle check above (several minutes)\n"
      "python -m microbiome.calibration report   # regenerates this file\n```")
    return "\n".join(out) + "\n"


def ts_roles(root) -> dict[str, str]:
    data = json.loads((root / "data" / "calibration_targets.json").read_text(encoding="utf-8"))
    return data["roles"]


def write(project_root=None) -> Path:
    root = Path(project_root).resolve() if project_root is not None else _PROJECT_ROOT
    path = root / DOC_FILE
    path.write_text(render(root), encoding="utf-8", newline="\n")
    return path
